//! WebAssembly bindings for the Geist4 Markdown engine, with TypeScript
//! types.
//!
//! The core builds for `wasm32-unknown-unknown` with no extra features, no
//! threads, and no file system access, so one engine serves browsers,
//! JavaScript server runtimes including edge runtimes, and native
//! applications alike. This crate is a shell until milestone M7; see the
//! repository roadmap.
