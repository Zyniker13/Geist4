//! A stable, C-compatible API for the Geist4 Markdown engine: the base for
//! native bindings such as the Swift package.
//!
//! The boundary follows decision 0028: opaque handles, explicit ownership,
//! UTF-8 in and out, and no panic ever crosses it — every entry point
//! catches and returns a [`Status`] code. Inputs are pointer-and-length
//! pairs, so a document's NUL bytes are ordinary content; outputs are
//! owned [`Geist4String`] values the caller releases with
//! `geist4_string_free`. The one `unsafe` in the workspace lives here,
//! confined to the handle plumbing the decision describes.
//!
//! See `include/geist4.h` (generated by `cbindgen`) for the C view, and
//! `c-tests/` for the C program that pins the contract.

use std::ffi::{CString, c_char};
use std::panic::{AssertUnwindSafe, catch_unwind};
use std::ptr;
use std::sync::{Arc, LazyLock};

use geist4_core::basic_html;
use geist4_core::extension::{Extension, Options};
use geist4_core::parser::{Document, parse_with};

/// The outcome of an FFI call.
///
/// Every fallible entry point returns this; anything but `GEIST4_OK`
/// leaves the output argument untouched and reports one line into the
/// caller's error buffer.
#[repr(i32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(non_camel_case_types, clippy::enum_variant_names)]
pub enum Status {
    /// The call succeeded.
    GEIST4_OK = 0,
    /// A required pointer argument was null.
    GEIST4_ERR_NULL = 1,
    /// The input bytes are not valid UTF-8; the error buffer names the
    /// byte offset.
    GEIST4_ERR_UTF8 = 2,
    /// The extension name is not one the engine knows; the error buffer
    /// lists the valid names.
    GEIST4_ERR_UNKNOWN_EXT = 3,
    /// Renderer output would have contained an interior NUL byte, which
    /// the engine never produces; this is an internal invariant failure.
    GEIST4_ERR_OUTPUT = 4,
    /// The engine panicked; the panic was caught at the boundary and the
    /// error buffer carries the message. This is always an engine bug.
    GEIST4_ERR_PANIC = 5,
}

/// An owned UTF-8 string the engine handed out.
///
/// `data` is always non-null and NUL-terminated; `len` counts the bytes
/// without the terminator. The caller owns the string and releases it
/// with `geist4_string_free`; mutating the bytes is allowed as long as
/// the NUL terminator stays in place.
#[repr(C)]
pub struct Geist4String {
    /// The bytes, NUL-terminated. Not null even when `len` is zero.
    pub data: *mut c_char,
    /// The number of bytes before the terminator.
    pub len: usize,
}

impl Geist4String {
    /// Wraps rendered output. Fails only if the output contained an
    /// interior NUL, which the engine never emits.
    fn from_output(text: String) -> Result<Self, String> {
        let Ok(cstring) = CString::new(text) else {
            return Err("renderer output contained an interior NUL byte".to_string());
        };
        let len = cstring.as_bytes().len();
        Ok(Geist4String {
            data: cstring.into_raw().cast::<c_char>(),
            len,
        })
    }
}

/// One problem the parse noticed in its source.
///
/// `message` points into memory the document handle owns: it stays
/// valid until that handle is freed.
#[repr(C)]
pub struct Geist4Problem {
    /// What the problem is, as one line, UTF-8, not NUL-terminated.
    pub message: *const c_char,
    /// The length of `message` in bytes.
    pub message_len: usize,
    /// The span's start, as a byte offset into the source.
    pub start: usize,
    /// The span's end, exclusive, as a byte offset into the source.
    pub end: usize,
}

/// A list of problems, borrowed from the document that produced it.
///
/// `items` is null only when `len` is zero. The memory belongs to the
/// `geist4_document`; it stays valid until that handle is freed.
#[repr(C)]
pub struct Geist4ProblemList {
    /// The problems, in document order.
    pub items: *const Geist4Problem,
    /// How many problems the list holds.
    pub len: usize,
}

/// The parse options: which built-in extensions are registered.
///
/// Created with `geist4_options_create`, configured with
/// `geist4_options_enable_builtin`, released with `geist4_options_free`.
/// Passing null where one is expected parses plain `CommonMark`.
pub struct OptionsHandle {
    options: Options,
}

/// A parsed document, owning the source it was parsed from.
///
/// The document borrows its text from the input, so the handle keeps a
/// private copy of the input alive (decision 0028). Release with
/// `geist4_document_free`; every pointer borrowed from the handle — the
/// problem messages — is invalid afterwards.
pub struct DocumentHandle {
    /// The input, leaked from a `Box<str>`; freed after the document.
    input: *mut str,
    /// The parsed document, whose borrows point into `input`. The
    /// `'static` lifetime is erased, not real: it holds exactly as long
    /// as `input` stays allocated, which this handle guarantees.
    document: *mut Document<'static>,
    /// The options the document was parsed with, so rendering needs no
    /// other argument and extensions outlive their options handle.
    options: Options,
    /// The problem entries handed to C, in document order.
    problems: Box<[Geist4Problem]>,
    /// The messages `problems` points into; same order, freed last.
    /// Never read directly — the entries' pointers reach the bytes —
    /// but the field must live as long as the handle or the pointers
    /// would dangle.
    #[allow(dead_code)]
    messages: Box<[Box<str>]>,
}

/// Plain `CommonMark`, for entry points called with a null options handle.
static PLAIN: LazyLock<Options> = LazyLock::new(Options::new);

/// The version of the engine, as a static NUL-terminated string the
/// caller never frees.
///
/// # Safety
/// The caller must not free or mutate the returned pointer.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_version() -> *const c_char {
    static VERSION: LazyLock<CString> = LazyLock::new(|| {
        CString::new(env!("CARGO_PKG_VERSION")).expect("a version number carries no NUL")
    });
    VERSION.as_ptr()
}

/// Creates an empty options handle: plain `CommonMark` until a built-in
/// is enabled.
#[must_use]
#[unsafe(no_mangle)]
pub extern "C" fn geist4_options_create() -> *mut OptionsHandle {
    Box::into_raw(Box::new(OptionsHandle {
        options: Options::new(),
    }))
}

/// Frees an options handle. Null is accepted and ignored, matching
/// `free(NULL)`. Documents already parsed with it keep working: they
/// hold their own copy of the registration.
///
/// # Safety
/// `options` must be null or a handle this library handed out that has
/// not been freed yet.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_options_free(options: *mut OptionsHandle) {
    if options.is_null() {
        return;
    }
    // SAFETY: the caller guarantees the handle came from
    // geist4_options_create and is live; see the safety contract.
    drop(unsafe { Box::from_raw(options) });
}

/// Registers a built-in extension by name.
///
/// Names: `tables`, `strikethrough`, `autolink`, `tasklist`,
/// `tagfilter`, `footnotes`, `front_matter`, `heading_identifiers`,
/// `description_lists`, and the bundles `gfm` (the five GitHub Flavored
/// Markdown ones) and `all` (every built-in). Enabling an extension
/// that is already registered does nothing, so bundles and single names
/// compose freely. Registration order is run order; a bundle inserts
/// its members in the engine's canonical order.
///
/// # Safety
/// `options` must be a live handle from `geist4_options_create`;
/// `name` must be readable for `name_len` bytes for the duration of the
/// call, or null when `name_len` is zero; `err` must be null or
/// writable for `err_cap` bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_options_enable_builtin(
    options: *mut OptionsHandle,
    name: *const c_char,
    name_len: usize,
    err: *mut c_char,
    err_cap: usize,
) -> Status {
    let Some(options) = (unsafe { options.as_mut() }) else {
        set_error(err, err_cap, "options handle is null");
        return Status::GEIST4_ERR_NULL;
    };
    let name_bytes: &[u8] = if name_len == 0 {
        &[]
    } else if name.is_null() {
        set_error(err, err_cap, "extension name pointer is null");
        return Status::GEIST4_ERR_NULL;
    } else {
        // SAFETY: the caller promises `name_len` readable bytes for the
        // duration of the call.
        unsafe { std::slice::from_raw_parts(name.cast::<u8>(), name_len) }
    };
    let Ok(name_str) = std::str::from_utf8(name_bytes) else {
        set_error(err, err_cap, "extension name is not valid UTF-8");
        return Status::GEIST4_ERR_UTF8;
    };
    let Some(added) = builtin_by_name(name_str) else {
        set_error(
            err,
            err_cap,
            "unknown extension; valid names: tables, strikethrough, autolink, \
             tasklist, tagfilter, footnotes, front_matter, heading_identifiers, \
             description_lists, gfm, all",
        );
        return Status::GEIST4_ERR_UNKNOWN_EXT;
    };
    for extension in added {
        // Idempotent: a name registered twice would run its hooks
        // twice, and no combination of these names should do that.
        if options.options.by_name(extension.name()).is_none() {
            options.options.extension(extension);
        }
    }
    Status::GEIST4_OK
}

/// The built-ins one name stands for, in registration order.
fn builtin_by_name(name: &str) -> Option<Vec<Arc<dyn Extension>>> {
    let one = |make: fn() -> Arc<dyn Extension>| vec![make()];
    match name {
        "tables" => Some(one(geist4_ext::tables)),
        "strikethrough" => Some(one(geist4_ext::strikethrough)),
        "autolink" => Some(one(geist4_ext::autolink)),
        "tasklist" => Some(one(geist4_ext::tasklist)),
        "tagfilter" => Some(one(geist4_ext::tagfilter)),
        "footnotes" => Some(one(geist4_ext::footnotes)),
        "front_matter" => Some(one(geist4_ext::front_matter)),
        "heading_identifiers" => Some(one(geist4_ext::heading_identifiers)),
        "description_lists" => Some(one(geist4_ext::deflists)),
        // The GitHub Flavored Markdown set, in the engine's canonical
        // registration order: block structure first, then the inline
        // triggers, then the output filter.
        "gfm" => Some(vec![
            geist4_ext::tables(),
            geist4_ext::strikethrough(),
            geist4_ext::autolink(),
            geist4_ext::tasklist(),
            geist4_ext::tagfilter(),
        ]),
        // Every built-in: front matter claims the prologue before block
        // parsing; footnotes, heading identifiers and description lists
        // post-process after it.
        "all" => Some(vec![
            geist4_ext::front_matter(),
            geist4_ext::tables(),
            geist4_ext::strikethrough(),
            geist4_ext::autolink(),
            geist4_ext::tasklist(),
            geist4_ext::tagfilter(),
            geist4_ext::footnotes(),
            geist4_ext::heading_identifiers(),
            geist4_ext::deflists(),
        ]),
        _ => None,
    }
}

/// Parses a document.
///
/// `options` may be null for plain `CommonMark`. The bytes must be
/// valid UTF-8; a NUL byte is ordinary content, as in any Markdown
/// source. `data` may be null only when `len` is zero, which parses an
/// empty document. On success the handle owns a copy of the input, so
/// the caller may free `data` as soon as the call returns. On failure
/// null is returned and the error buffer explains why.
///
/// # Safety
/// `data` must be readable for `len` bytes for the duration of the
/// call, or null when `len` is zero; `err` must be null or writable for
/// `err_cap` bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_parse(
    options: *const OptionsHandle,
    data: *const c_char,
    len: usize,
    err: *mut c_char,
    err_cap: usize,
) -> *mut DocumentHandle {
    let Ok(source) = validate_input(data, len, err, err_cap) else {
        return ptr::null_mut();
    };
    let options_ref: &Options = if options.is_null() {
        &PLAIN
    } else {
        // SAFETY: non-null, from geist4_options_create, still live.
        unsafe { &(*options).options }
    };
    build_handle(source, options_ref, err, err_cap)
}

/// Copies `source` into a handle-owned allocation, parses it there, and
/// boxes the result with the problem lists laid out for C.
///
/// The `'static` borrows inside the returned handle are erased, not
/// real: they hold exactly as long as the input allocation does, and
/// `geist4_document_free` frees the document before the input (decision
/// 0028).
fn build_handle(
    source: &str,
    options: &Options,
    err: *mut c_char,
    err_cap: usize,
) -> *mut DocumentHandle {
    let input: Box<str> = Box::from(source);
    let input_ptr: *mut str = Box::into_raw(input);
    // SAFETY: `input_ptr` is the live allocation of the Box just
    // constructed; it stays allocated until geist4_document_free, and
    // nothing writes through it afterwards.
    let source: &str = unsafe { &*input_ptr };
    let parsed = catch_unwind(AssertUnwindSafe(|| parse_with(source, options)));
    let document = match parsed {
        Ok(document) => document,
        Err(panic) => {
            // SAFETY: the same pointer into_raw handed out, not yet
            // freed; the parse failed, so nothing borrows it.
            drop(unsafe { Box::from_raw(input_ptr) });
            set_error(err, err_cap, &panic_message(&panic));
            return ptr::null_mut();
        }
    };
    // The problem list: one boxed message per problem, and a C entry
    // pointing into it. The messages' heap addresses never change, so
    // the entries stay valid for the handle's whole life.
    let mut messages: Vec<Box<str>> = Vec::with_capacity(document.problems.len());
    let mut entries: Vec<Geist4Problem> = Vec::with_capacity(document.problems.len());
    for problem in &document.problems {
        let message: Box<str> = problem.message.as_str().into();
        let entry = Geist4Problem {
            message: message.as_ptr().cast::<c_char>(),
            message_len: message.len(),
            start: problem.span.start,
            end: problem.span.end,
        };
        messages.push(message);
        entries.push(entry);
    }
    let handle = DocumentHandle {
        input: input_ptr,
        document: Box::into_raw(Box::new(document)),
        options: options.clone(),
        problems: entries.into_boxed_slice(),
        messages: messages.into_boxed_slice(),
    };
    Box::into_raw(Box::new(handle))
}

/// Renders a parsed document's HTML into an owned string.
///
/// The extensions registered on the options the document was parsed
/// with render the node kinds they declared, exactly as in the Rust
/// API. On failure `out` is untouched.
///
/// # Safety
/// `document` must be a live handle from `geist4_parse`; `out` must be
/// writable; `err` must be null or writable for `err_cap` bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_document_html(
    document: *const DocumentHandle,
    out: *mut Geist4String,
    err: *mut c_char,
    err_cap: usize,
) -> Status {
    let Some(document) = (unsafe { document.as_ref() }) else {
        set_error(err, err_cap, "document handle is null");
        return Status::GEIST4_ERR_NULL;
    };
    if out.is_null() {
        set_error(err, err_cap, "output pointer is null");
        return Status::GEIST4_ERR_NULL;
    }
    // SAFETY: the handle's document points into its own input, which
    // stays allocated until geist4_document_free; see decision 0028.
    let render = catch_unwind(AssertUnwindSafe(|| {
        let tree = unsafe { &*document.document };
        basic_html::render_with(tree, &document.options)
    }));
    match render {
        Ok(html) => write_string(html, out, err, err_cap),
        Err(panic) => {
            set_error(err, err_cap, &panic_message(&panic));
            Status::GEIST4_ERR_PANIC
        }
    }
}

/// The document's problems: broken references and similar issues the
/// tree absorbed without changing the output.
///
/// The list borrows from the document; it stays valid until
/// `geist4_document_free`. An empty list means no problems, not a null
/// pointer.
///
/// # Safety
/// `document` must be a live handle from `geist4_parse`; `out` must be
/// writable; `err` must be null or writable for `err_cap` bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_document_problems(
    document: *const DocumentHandle,
    out: *mut Geist4ProblemList,
    err: *mut c_char,
    err_cap: usize,
) -> Status {
    let Some(document) = (unsafe { document.as_ref() }) else {
        set_error(err, err_cap, "document handle is null");
        return Status::GEIST4_ERR_NULL;
    };
    if out.is_null() {
        set_error(err, err_cap, "output pointer is null");
        return Status::GEIST4_ERR_NULL;
    }
    let list = Geist4ProblemList {
        items: document.problems.as_ptr(),
        len: document.problems.len(),
    };
    // SAFETY: `out` was checked non-null and is writable.
    unsafe { *out = list };
    Status::GEIST4_OK
}

/// Frees a document handle and everything it owns: the document, its
/// private copy of the input, and the problem messages. Null is
/// accepted and ignored. Every pointer borrowed from the handle — the
/// problem messages — is invalid afterwards.
///
/// # Safety
/// `document` must be null or a handle this library handed out that has
/// not been freed yet.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_document_free(document: *mut DocumentHandle) {
    if document.is_null() {
        return;
    }
    // SAFETY: the caller guarantees the handle came from geist4_parse
    // and is live. The two raw pointers are exactly the ones the
    // constructor handed out; the document borrows the input, so it is
    // dropped first.
    let handle = unsafe { Box::from_raw(document) };
    // SAFETY: `handle.document` came from `Box::into_raw` at parse time
    // and has not been dropped yet.
    drop(unsafe { Box::from_raw(handle.document) });
    // SAFETY: `handle.input` came from `Box::into_raw` at parse time;
    // with the document gone nothing borrows it any more.
    drop(unsafe { Box::from_raw(handle.input) });
}

/// Parses and renders in one call, without a document handle.
///
/// The convenient path for callers who only want HTML: on success `out`
/// holds the rendered document and the intermediate tree never leaves
/// this function. Semantics match `geist4_parse` followed by
/// `geist4_document_html`.
///
/// # Safety
/// `data` must be readable for `len` bytes for the duration of the
/// call, or null when `len` is zero; `out` must be writable; `err` must
/// be null or writable for `err_cap` bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_render_html(
    options: *const OptionsHandle,
    data: *const c_char,
    len: usize,
    out: *mut Geist4String,
    err: *mut c_char,
    err_cap: usize,
) -> Status {
    let source = match validate_input(data, len, err, err_cap) {
        Ok(source) => source,
        Err(status) => return status,
    };
    if out.is_null() {
        set_error(err, err_cap, "output pointer is null");
        return Status::GEIST4_ERR_NULL;
    }
    let options_ref: &Options = if options.is_null() {
        &PLAIN
    } else {
        // SAFETY: non-null, from geist4_options_create, still live.
        unsafe { &(*options).options }
    };
    let input: Box<str> = Box::from(source);
    let input_ptr: *mut str = Box::into_raw(input);
    // SAFETY: the allocation just constructed; freed on every path
    // below before returning.
    let source: &str = unsafe { &*input_ptr };
    let rendered = catch_unwind(AssertUnwindSafe(|| {
        let document = parse_with(source, options_ref);
        basic_html::render_with(&document, options_ref)
    }));
    // SAFETY: the same pointer into_raw handed out, not yet freed, and
    // after this point nothing borrows it.
    drop(unsafe { Box::from_raw(input_ptr) });
    match rendered {
        Ok(html) => write_string(html, out, err, err_cap),
        Err(panic) => {
            set_error(err, err_cap, &panic_message(&panic));
            Status::GEIST4_ERR_PANIC
        }
    }
}

/// Frees a string the engine handed out. Null data is accepted and
/// ignored. After the call the string's bytes are invalid.
///
/// # Safety
/// `value.data` must be null or a pointer one of this library's output
/// entry points handed out, freed exactly once; the allocation must not
/// have been grown or replaced by the caller.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn geist4_string_free(value: Geist4String) {
    if value.data.is_null() {
        return;
    }
    // SAFETY: the pointer came from `CString::into_raw` in
    // `Geist4String::from_output` and has not been freed yet; the
    // caller may have mutated the bytes but not the allocation.
    drop(unsafe { CString::from_raw(value.data) });
}

/// Validates the `(data, len)` input pair and returns it as a `&str`,
/// or the status code that explains the rejection (with the error
/// buffer already filled).
///
/// Returns `Err` when the pointer is null or the bytes are not UTF-8.
fn validate_input(
    data: *const c_char,
    len: usize,
    err: *mut c_char,
    err_cap: usize,
) -> Result<&'static str, Status> {
    if data.is_null() {
        if len == 0 {
            // No buffer and no bytes: an empty document, as in cmark.
            return Ok("");
        }
        set_error(err, err_cap, "input pointer is null");
        return Err(Status::GEIST4_ERR_NULL);
    }
    // SAFETY: the caller promises `len` readable bytes for the duration
    // of the call.
    let bytes = unsafe { std::slice::from_raw_parts(data.cast::<u8>(), len) };
    match std::str::from_utf8(bytes) {
        Ok(source) => {
            // The reborrow to 'static is the caller's duration-of-call
            // promise: nothing keeps this reference past the entry
            // point, and the copy into the handle happens inside it.
            Ok(source)
        }
        Err(error) => {
            set_error(
                err,
                err_cap,
                &format!("input is not valid UTF-8 at byte {}", error.valid_up_to()),
            );
            Err(Status::GEIST4_ERR_UTF8)
        }
    }
}

/// Writes `message` into the caller's error buffer, truncated to fit
/// and always NUL-terminated; a null buffer or zero capacity drops the
/// message.
fn set_error(err: *mut c_char, err_cap: usize, message: &str) {
    if err.is_null() || err_cap == 0 {
        return;
    }
    let bytes = message.as_bytes();
    let kept = bytes.len().min(err_cap - 1);
    // SAFETY: the caller promises `err` is writable for `err_cap`
    // bytes; `kept + 1 <= err_cap`.
    unsafe {
        ptr::copy_nonoverlapping(bytes.as_ptr(), err.cast::<u8>(), kept);
        *err.add(kept) = 0;
    }
}

/// Wraps output into a [`Geist4String`] and stores it through `out`,
/// or reports why that failed.
fn write_string(html: String, out: *mut Geist4String, err: *mut c_char, err_cap: usize) -> Status {
    match Geist4String::from_output(html) {
        Ok(value) => {
            // SAFETY: every caller checked `out` non-null and writable
            // before calling.
            unsafe { *out = value };
            Status::GEIST4_OK
        }
        Err(message) => {
            set_error(err, err_cap, &message);
            Status::GEIST4_ERR_OUTPUT
        }
    }
}

/// The message a caught panic carries, for the error buffer.
fn panic_message(panic: &Box<dyn std::any::Any + Send>) -> String {
    if let Some(text) = panic.downcast_ref::<&str>() {
        (*text).to_string()
    } else if let Some(text) = panic.downcast_ref::<String>() {
        text.clone()
    } else {
        "the engine panicked without a message".to_string()
    }
}
