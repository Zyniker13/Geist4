#!/usr/bin/env python3
"""The cross-binding suite's driver: every binding must render the case
list (`tests/bindings/cases.jsonl`, generated by `tools/gen_cross_cases.py`)
byte for byte as the Rust core does.

The reference is `geist4-ffi`'s `cross_reference` binary, which renders
through the same safe surface every binding calls; each binding's
runner writes the same JSON-lines shape. A binding differs if any
case's html differs, if a case is missing, or if a runner crashes.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / "tests" / "bindings" / "cases.jsonl"


def load(path: Path) -> list[tuple[str, str]]:
    records = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            if not line:
                continue
            record = json.loads(line)
            records.append((record["name"], record["html"]))
    return records


def run_binding(label: str, command: list[str], results: Path) -> None:
    completed = subprocess.run(
        command + [str(CASES), str(results)],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if completed.returncode != 0:
        message = (completed.stderr or completed.stdout or "").strip().splitlines()
        detail = "\n".join(message[-5:])
        raise SystemExit(f"{label}: the runner failed (exit {completed.returncode}):\n{detail}")


def compare(label: str, expected: list[tuple[str, str]], actual: list[tuple[str, str]]) -> None:
    if len(actual) != len(expected):
        raise SystemExit(
            f"{label}: {len(actual)} results for {len(expected)} cases"
        )
    shown = 0
    for (want_name, want_html), (got_name, got_html) in zip(expected, actual):
        if want_name != got_name:
            raise SystemExit(f"{label}: results out of order at {want_name!r} vs {got_name!r}")
        if want_html != got_html:
            if shown < 3:
                print(f"DIFF {label} {want_name}:", file=sys.stderr)
                print(f"  core:    {want_html[:200]!r}", file=sys.stderr)
                print(f"  {label}: {got_html[:200]!r}", file=sys.stderr)
            shown += 1
    if shown:
        raise SystemExit(f"{label}: {shown} of {len(expected)} cases differ from the core")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", required=True, help="the cross_reference binary")
    parser.add_argument("--node", help="the node executable; JavaScript is checked when given")
    parser.add_argument("--python", help="the python with geist4 installed; Python is checked when given")
    parser.add_argument("--swift", help="the Geist4Cross binary; Swift is checked when given")
    args = parser.parse_args()

    bindings: list[tuple[str, list[str]]] = []
    if args.node:
        bindings.append(("javascript", [args.node, "crates/geist4-wasm/node-tests/cross.mjs"]))
    if args.python:
        bindings.append(("python", [args.python, "crates/geist4-python/tests/cross_binding.py"]))
    if args.swift:
        bindings.append(("swift", [args.swift]))

    with tempfile.TemporaryDirectory(prefix="geist4-cross-") as tmp:
        tmp_path = Path(tmp)
        reference_results = tmp_path / "core.jsonl"
        run_binding("core", [args.reference], reference_results)
        expected = load(reference_results)
        print(f"cross-binding: {len(expected)} cases against the core")
        for label, command in bindings:
            results = tmp_path / f"{label}.jsonl"
            run_binding(label, command, results)
            compare(label, expected, load(results))
            print(f"cross-binding: {label} matches the core byte for byte")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
